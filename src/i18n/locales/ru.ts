/** Russian plural form: 1 повтор, 2 повтора, 5 повторов, 11 повторов, 21 повтор. */
function form(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(Math.trunc(n)) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}
const plural = (n: number, one: string, few: string, many: string) => `${n} ${form(n, one, few, many)}`;
/** After «из» the noun is genitive: из 1 повтора, из 21 повтора, из 10 повторов. */
const ofForm = (n: number, gSg: string, gPl: string) => {
  const a = Math.abs(Math.trunc(n)) % 100;
  return a % 10 === 1 && a !== 11 ? gSg : gPl;
};

