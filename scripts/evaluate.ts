/**
 * End-to-end evaluation of the coaching engine on public data.
 *
 *   node scripts/evaluate.ts            # → docs/evaluation.md
 *
 * For each UI-PRMD-mapped exercise and each subject, all 10 episodes are stitched into one
 * continuous stream (with short rests between reps), rendered through a virtual webcam, corrupted
 * with MediaPipe-like landmark jitter, smoothed with the app's One Euro filter, and fed frame by
 * frame into the exact CoachEngine the browser uses (side auto-detection, gates, rep state machine,
 * debounced checks — everything).
 *
 * We report: rep-count accuracy on correct executions, and how often reps get flagged (fault cue
 * or short of range) for correct vs. deliberately non-optimal executions.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { EXERCISES, UIPRMD_MAP } from "../src/coach/exercises.ts";
import { CoachEngine, type RepRecord } from "../src/coach/engine.ts";
import { PoseSmoother } from "../src/pose/filter.ts";
import type { PoseFrame } from "../src/pose/landmarks.ts";
import { loadEpisodes, MOVEMENTS } from "./lib/uiprmd.ts";
import { replay } from "./lib/episodes.ts";

const NOISE = Number(process.env.NOISE ?? 0.004); // frame heights (~0.9 cm at 2.3 m field of view)
const GOAL = Number(process.env.GOAL ?? 0.8);
const REST_FRAMES = 20;
const ROOT = join(import.meta.dirname, "..");

interface Result {
  episodes: number;
  reps: RepRecord[];
  expected: number;
}

function run(exId: string, split: "correct" | "incorrect"): Result {
  const ex = EXERCISES.find((e) => e.id === exId)!;
  const episodes = loadEpisodes(UIPRMD_MAP[exId], split);
  const bySubject = new Map<number, typeof episodes>();
  for (const e of episodes) bySubject.set(e.subject, [...(bySubject.get(e.subject) ?? []), e]);
  const reps: RepRecord[] = [];
  let expected = 0;
  for (const [, eps] of bySubject) {
    const engine = new CoachEngine(ex, { rangeGoal: GOAL, reps: 1000, holdSeconds: 1000 });
    const smoother = new PoseSmoother();
    let t = 0;
    const feed = (f: PoseFrame) => {
      t += 1000 / 30;
      const st = engine.update(smoother.apply({ ...f, t }));
      for (const ev of st.events) if (ev.type === "rep") reps.push(ev.rep);
    };
    for (const ep of eps) {
      const { frames } = replay(ex, ep, NOISE);
      for (let i = 0; i < REST_FRAMES; i++) feed(frames[0]);
      for (const f of frames) feed(f);
      for (let i = 0; i < REST_FRAMES; i++) feed(frames[frames.length - 1]);
    }
    // sit-to-stand recordings go stand→sit→stand; coached seated→standing→seated, so the last stand never closes
    expected += ex.primary.startIsExcursion ? eps.length - 1 : eps.length;
  }
  return { episodes: episodes.length, reps, expected };
}

const pct = (x: number) => `${Math.round(100 * x)}%`;
const flagged = (r: RepRecord) => !r.full || r.faults.some((f) => f !== "tempo");
const rushed = (r: RepRecord) => r.faults.includes("tempo");

const md = [
  "# Engine evaluation on UI-PRMD",
  "",
  `Generated by \`node scripts/evaluate.ts\` · landmark jitter σ = ${NOISE} frame-heights · range goal ${Math.round(GOAL * 100)}%.`,
  "",
  "Each subject's 10 recorded reps are stitched into one continuous stream and played frame-by-frame through the",
  "same smoothing + `CoachEngine` the browser uses. *Flagged* = the rep received a form cue or fell short of the range goal",
"(tempo \"slow down\" cues are reported separately — they are a coaching preference, not a UI-PRMD error label).",
  "A rep that never reaches 70% of the goal isn't counted at all (the coach says \"go a little further\").",
  "",
  "| Exercise | UI-PRMD | Reps counted (correct) | Flagged · correct | Counted (incorrect) | Flagged or not counted · incorrect | Tempo cue · correct | Mean score correct → incorrect |",
  "|---|---|---|---|---|---|---|---|",
];
let totGood = 0, totGoodExp = 0;
for (const ex of EXERCISES) {
  const mv = UIPRMD_MAP[ex.id];
  if (!mv) continue;
  const g = run(ex.id, "correct");
  const b = run(ex.id, "incorrect");
  totGood += Math.min(g.reps.length, g.expected);
  totGoodExp += g.expected;
  const score = (r: RepRecord[]) => (r.length ? Math.round(r.reduce((a, x) => a + x.score, 0) / r.length) : NaN);
  // an incorrect rep that wasn't counted is also "caught" (too shallow)
  const badCaught = (b.reps.filter(flagged).length + Math.max(0, b.expected - b.reps.length)) / b.expected;
  const row = `| ${ex.name} | ${mv} ${MOVEMENTS[mv]} | ${g.reps.length}/${g.expected} | ${pct(g.reps.filter(flagged).length / Math.max(1, g.reps.length))} | ${b.reps.length}/${b.expected} | ${pct(badCaught)} | ${pct(g.reps.filter(rushed).length / Math.max(1, g.reps.length))} | ${score(g.reps)} → ${score(b.reps)} |`;
  md.push(row);
  const faultCounts = (r: RepRecord[]) => {
    const m: Record<string, number> = {};
    for (const x of r) for (const f of x.faults) m[f] = (m[f] ?? 0) + 1;
    return Object.entries(m).map(([k, v]) => `${k}:${v}`).join(" ");
  };
  console.log(`${ex.id.padEnd(20)} correct ${g.reps.length}/${g.expected} flagged ${pct(g.reps.filter(flagged).length / Math.max(1, g.reps.length))} [${faultCounts(g.reps)}] notFull ${g.reps.filter((r) => !r.full).length} | incorrect ${b.reps.length}/${b.expected} caught ${pct(badCaught)} [${faultCounts(b.reps)}]`);
}
md.push("", `**Overall rep-count recall on correct executions: ${totGood}/${totGoodExp} (${pct(totGood / totGoodExp)}).**`, "");
md.push(
  "Known weak spots: the straight-leg-raise knee check fires on correct reps because Kinect v2 loses the knee when the leg",
  "points at the sensor (a dataset artifact). Shoulder-extension subjects sometimes switched arms between reps, while the coach",
  "locks onto one arm per set. Sit-to-stand \"incorrect\" reps (balance, weight shift) are invisible to these 2D checks.",
  "",
);
md.push(
  "Caveats: UI-PRMD subjects are healthy adults acting out \"non-optimal\" reps (no per-rep fault labels), the Kinect v2",
  "skeleton has its own tracking errors (notably knees during the straight-leg raise), and a virtual camera is not a real",
  "webcam. Treat these numbers as a smoke test of the full pipeline, not clinical validation.",
);
mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(join(ROOT, "docs", "evaluation.md"), md.join("\n") + "\n");
console.log("wrote docs/evaluation.md");
