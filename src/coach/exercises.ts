/**
 * Exercise library.
 *
 * Eight movements come from the UI-PRMD rehab protocol (Vakanski et al. 2018). For those, the
 * range-of-motion reference (`primary.start` / `primary.target`) is computed from the dataset's
 * correctly-performed Kinect recordings by `scripts/calibrate.ts` (→ src/data/calibration.json),
 * and the form-check thresholds start from the paper's "non-optimal movement" criteria (Table 1).
 * The rest use AAOS normative joint ranges and common clinical prescriptions.
 */
import calibration from "../data/calibration.json" with { type: "json" };
import type { ExerciseDef, PrimaryMotion } from "./types.ts";

interface CalEntry { rest: number; excursion: number; n: number; subjects: number; lowerMsP10?: number }
const CAL = (calibration as { exercises: Record<string, CalEntry> }).exercises ?? {};

/** "Lower slowly" threshold: 0.8 × the fastest-10% lowering phase of UI-PRMD's healthy reps (rounded to 50 ms),
 *  so only a genuine drop is flagged. Falls back to a clinical default when there's no calibration data. */
function lowerMs(id: string, fallback: number): number {
  const p10 = CAL[id]?.lowerMsP10;
  return p10 ? Math.round((0.8 * p10) / 50) * 50 : fallback;
}

/** Primary motion with the reference range from UI-PRMD when calibration data exists. */
function calibrated(id: string, base: PrimaryMotion): PrimaryMotion {
  const c = CAL[id];
  if (!c) return base;
  const [start, target] = base.startIsExcursion ? [c.excursion, c.rest] : [c.rest, c.excursion];
  return {
    ...base,
    start: Math.round(start),
    target: Math.round(target),
    basis: `UI-PRMD: median of ${c.n} correct reps from ${c.subjects} healthy adults (Kinect v2).`,
  };
}

