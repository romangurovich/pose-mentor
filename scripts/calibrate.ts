/**
 * Calibrate exercise reference ranges from the public UI-PRMD dataset.
 *
 *   python3 scripts/fetch_uiprmd.py      # once
 *   node scripts/calibrate.ts            # → src/data/calibration.json + docs/calibration.md
 *
 * For every exercise mapped to a UI-PRMD movement we replay each Kinect episode through a virtual
 * webcam (same 33-landmark 2D representation as MediaPipe), measure the exercise's primary metric
 * with the app's own metric code, and take robust statistics over the correctly-performed reps:
 *   start  = median over episodes of the starting value
 *   target = median over episodes of the end-range (peak) value
 * We also report, for each form check, how its metric is distributed on correct vs. incorrect reps
 * so thresholds can be sanity-checked against data.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { EXERCISES, UIPRMD_MAP } from "../src/coach/exercises.ts";
import { METRICS } from "../src/coach/metrics.ts";
import type { ExerciseDef } from "../src/coach/types.ts";
import { loadEpisodes, MOVEMENTS } from "./lib/uiprmd.ts";
import { analyseEpisode, median, q, r1, type EpisodeStats } from "./lib/analyse.ts";

const ROOT = join(import.meta.dirname, "..");

function analyse(ex: ExerciseDef, split: "correct" | "incorrect"): { eps: EpisodeStats[]; subjects: number } {
  const episodes = loadEpisodes(UIPRMD_MAP[ex.id], split);
  return { eps: episodes.map((ep) => analyseEpisode(ex, ep)), subjects: new Set(episodes.map((e) => e.subject)).size };
}

const calibration: Record<string, unknown> = {};
const md: string[] = [
  "# UI-PRMD calibration report",
  "",
  "Generated by `node scripts/calibrate.ts` from the public [UI-PRMD](https://doi.org/10.3390/data3010002) Kinect v2 recordings",
  "(10 healthy adults × 10 reps per movement, correct and deliberately non-optimal executions).",
  "Each recording is replayed through a virtual webcam into the same 2D landmark format MediaPipe produces,",
  "then measured with the app's own metric code.",
  "",
];

for (const ex of EXERCISES) {
  const mv = UIPRMD_MAP[ex.id];
  if (!mv) continue;
  const good = analyse(ex, "correct");
  const bad = analyse(ex, "incorrect");
  const rests = good.eps.map((e) => e.rest);
  const peaks = good.eps.map((e) => e.excursion);
  const badPeaks = bad.eps.map((e) => e.excursion);
  const entry = {
    movement: `${mv} ${MOVEMENTS[mv]}`,
    metric: ex.primary.metric,
    rest: r1(median(rests)),
    excursion: r1(median(peaks)),
    excursionP10: r1(q(peaks, 0.1)),
    excursionP90: r1(q(peaks, 0.9)),
    incorrectExcursionMedian: r1(median(badPeaks)),
    lowerMsP10: Math.round(q(good.eps.flatMap((e) => (e.lowerMs === undefined ? [] : [e.lowerMs])), 0.1)),
    lowerMsMedian: Math.round(median(good.eps.flatMap((e) => (e.lowerMs === undefined ? [] : [e.lowerMs])))),
    n: good.eps.length,
    subjects: good.subjects,
  };
  calibration[ex.id] = entry;

  md.push(`## ${ex.name} — ${mv} ${MOVEMENTS[mv]}`, "");
  md.push(`Primary metric **${METRICS[ex.primary.metric].label}** (${ex.view} view), ${entry.n} correct / ${bad.eps.length} incorrect episodes.`, "");
  if (ex.primary.startIsExcursion) md.push("_Coached in reverse: the start position is the recordings' end-range (seated)._", "");
  md.push("| | rest (median) | excursion p10 | **excursion median** | excursion p90 |", "|---|---|---|---|---|");
  md.push(`| correct | ${entry.rest}° | ${entry.excursionP10}° | **${entry.excursion}°** | ${entry.excursionP90}° |`);
  md.push(`| incorrect | ${r1(median(bad.eps.map((e) => e.rest)))}° | ${r1(q(badPeaks, 0.1))}° | ${entry.incorrectExcursionMedian}° | ${r1(q(badPeaks, 0.9))}° |`, "");
  const badLower = bad.eps.flatMap((e) => (e.lowerMs === undefined ? [] : [e.lowerMs]));
  md.push(
    `Lowering phase (${ex.lowerPhase === "out" ? "descent" : "return to start"}): correct p10 **${entry.lowerMsP10} ms**, median ${entry.lowerMsMedian} ms · incorrect p10 ${Math.round(q(badLower, 0.1))} ms, median ${Math.round(median(badLower))} ms` +
      (ex.minLowerMs ? ` · "lower slowly" below ${ex.minLowerMs} ms.` : "."),
    "",
  );
  if (ex.checks.length) {
    md.push("| form check | threshold | correct p50 / p90 | incorrect p50 / p90 | flagged: correct | flagged: incorrect |", "|---|---|---|---|---|---|");
    for (const c of ex.checks) {
      const g = good.eps.map((e) => e.checks[c.id]).filter((x) => x !== undefined);
      const b = bad.eps.map((e) => e.checks[c.id]).filter((x) => x !== undefined);
      const hit = (xs: number[]) => xs.filter((x) => (c.op === ">" ? x > c.threshold : x < c.threshold)).length / Math.max(1, xs.length);
      const pick = (xs: number[], p: number) => r1(q(xs, c.op === ">" ? p : 1 - p));
      md.push(
        `| ${c.label}${c.relative ? " (Δ)" : ""}${c.maxProgress !== undefined ? ` (≤${Math.round(c.maxProgress * 100)}% of range)` : ""} | ${c.op} ${c.threshold}${METRICS[c.metric].unit} | ${pick(g, 0.5)} / ${pick(g, 0.9)} | ${pick(b, 0.5)} / ${pick(b, 0.9)} | ${Math.round(100 * hit(g))}% | ${Math.round(100 * hit(b))}% |`,
      );
    }
    md.push("");
  }
  console.log(`${ex.id.padEnd(20)} ${mv}  rest ${entry.rest}  excursion ${entry.excursion}  (p10 ${entry.excursionP10}, p90 ${entry.excursionP90})  incorrect ${entry.incorrectExcursionMedian}`);
}

const out = {
  source: "UI-PRMD — Vakanski et al., Data 2018, 3(1):2 (ODC PDDL). Kinect v2, segmented episodes.",
  generatedBy: "scripts/calibrate.ts",
  exercises: calibration,
};
writeFileSync(join(ROOT, "src", "data", "calibration.json"), JSON.stringify(out, null, 2) + "\n");
mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(join(ROOT, "docs", "calibration.md"), md.join("\n") + "\n");
console.log("wrote src/data/calibration.json and docs/calibration.md");
