/**
 * Check exercises UI-PRMD doesn't cover (and cross-check some it does) against Rehab-Pile.
 *
 *   python3 scripts/fetch_rehabpile.py       # once
 *   node scripts/calibrate-rehabpile.ts      # → docs/calibration-rehabpile.md
 *
 * Each recording is converted to the UI-PRMD joint layout, rendered through the same virtual webcam, and
 * measured with the app's own metric code (scripts/lib/analyse.ts). Recordings are split into a "good" and a
 * "poor" group from the dataset's own labels, and we report the range reached and how often every form check
 * fires in each group at its current threshold.
 *
 * Rehab-Pile resamples every recording to a fixed length, so nothing here says anything about timing.
 * Only standing recordings are used (the app coaches these moves standing); seated ones are counted but excluded.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { getExercise } from "../src/coach/exercises.ts";
import { METRICS } from "../src/coach/metrics.ts";
import type { ExerciseDef } from "../src/coach/types.ts";
import { loadRehabPile, type RPEpisode } from "./lib/rehabpile.ts";
import { analyseEpisode, median, q, r1, type EpisodeStats } from "./lib/analyse.ts";

const ROOT = join(import.meta.dirname, "..");

interface Study {
  exercise: string;
  datasets: string[];
  source: string;
  good: { name: string; test: (e: RPEpisode) => boolean };
  poor: { name: string; test: (e: RPEpisode) => boolean };
  /** checks whose metric depends on joints this dataset doesn't have (synthesised) */
  skip?: string[];
  note?: string;
}

const IRDS = "IntelliRehabDS (Miron et al. 2021) — Kinect v2, healthy adults and patients, therapist-labelled correct / incorrect";
const KIMORE = "KIMORE (Capecci et al. 2019) — Kinect v2, healthy adults and patients with low-back pain, Parkinson's or stroke; clinical score 0–100";
const KERAAL = "KERAAL (Nguyen et al. 2024) — Kinect v2 upper body (no legs), low-back-pain patients; correct + three error classes";
const irdsGood = { name: "correct", test: (e: RPEpisode) => e.label === 1 };
const irdsPoor = { name: "incorrect", test: (e: RPEpisode) => e.label === 2 };
const kimoreGood = { name: "score ≥ 80", test: (e: RPEpisode) => typeof e.label === "number" && e.label >= 80 };
const kimorePoor = { name: "score < 50", test: (e: RPEpisode) => typeof e.label === "number" && e.label < 50 };

const STUDIES: Study[] = [
  { exercise: "shoulder-flexion", datasets: ["IRDS_clf_bn_SFL", "IRDS_clf_bn_SFR"], source: IRDS, good: irdsGood, poor: irdsPoor },
  { exercise: "shoulder-abduction", datasets: ["IRDS_clf_bn_SAL", "IRDS_clf_bn_SAR"], source: IRDS, good: irdsGood, poor: irdsPoor, note: "Cross-check of the UI-PRMD calibration on a population that includes patients." },
  {
    exercise: "hip-abduction",
    datasets: ["IRDS_clf_bn_STL", "IRDS_clf_bn_STR"],
    source: IRDS,
    good: irdsGood,
    poor: irdsPoor,
    note: "IRDS *side tap* (tap the foot out to the side) is a smaller movement than a held hip abduction, so its range isn't used for the target — only to check that the compensation checks stay quiet on correct reps.",
  },
  {
    exercise: "side-bend",
    datasets: ["KIMORE_reg_LT"],
    source: KIMORE,
    good: kimoreGood,
    poor: kimorePoor,
    note: "KIMORE's lateral tilt is done with the arms raised overhead and bends to both sides in one recording; the range is measured toward the side that bends further.",
  },
  {
    exercise: "side-bend",
    datasets: ["KERAAL_clf_mc_ELK"],
    source: KERAAL,
    good: { name: "correct (C)", test: (e) => e.label === "C" },
    poor: { name: "errors (E1–E3)", test: (e) => e.label !== "C" },
    skip: ["shift"],
    note: "KERAAL has no hip or leg joints; hips are synthesised beside the pelvis, so hip-shift can't be measured. The three error classes aren't described in the archive; E2 bends noticeably less than correct reps.",
  },
  { exercise: "squat", datasets: ["KIMORE_reg_Sq"], source: KIMORE, good: kimoreGood, poor: kimorePoor, note: "Cross-check of the UI-PRMD (healthy, deep squat) calibration on patients' partial squats." },
];

const md: string[] = [
  "# Rehab-Pile cross-check",
  "",
  "Generated by `node scripts/calibrate-rehabpile.ts` from [Rehab-Pile](https://msd-irimas.github.io/pages/DeepRehabPile/)",
  "(Ismail-Fawaz et al., FG 2026), which redistributes several public rehabilitation skeleton datasets.",
  "Each recording is converted to the UI-PRMD joint layout, rendered through the same virtual webcam as the UI-PRMD",
  "calibration, and measured with the app's own metric code. *Flagged* = share of recordings in which the check would fire",
  "at its current threshold (worst value over the recording, in the phase where the check is active).",
  "",
  "Rehab-Pile resamples recordings to a fixed length, so timing (tempo, lowering speed) can't be checked here.",
  "Only standing recordings are used. The Elderly Home Exercise set was left out: its 0–10 score scale isn't documented and",
  "its highest-scored waist bends move the least, so the labels couldn't be interpreted with confidence.",
  "",
];

function stats(ex: ExerciseDef, eps: RPEpisode[]) {
  return eps.map((e) => analyseEpisode(ex, e, { directional: true }));
}

for (const st of STUDIES) {
  const ex = getExercise(st.exercise);
  const all = st.datasets.flatMap((d) => loadRehabPile(d));
  const standing = all.filter((e) => !e.seated);
  const good = stats(ex, standing.filter(st.good.test));
  const poor = stats(ex, standing.filter(st.poor.test));
  const subjects = new Set(standing.map((e) => e.subject)).size;

  md.push(`## ${ex.name} ← ${st.datasets.join(", ")}`, "", st.source + ".", "");
  if (st.note) md.push(st.note, "");
  md.push(`${standing.length} standing recordings from ${subjects} people (${all.length - standing.length} seated excluded).`, "");
  md.push(`Primary metric **${METRICS[ex.primary.metric].label}** · app reference ${ex.primary.start}° → **${ex.primary.target}°**.`, "");
  md.push("| group | n | start (median) | end-range p10 | **end-range median** | end-range p90 |", "|---|---|---|---|---|---|");
  const row = (name: string, g: EpisodeStats[]) => {
    const x = g.map((e) => e.excursion);
    md.push(`| ${name} | ${g.length} | ${r1(median(g.map((e) => e.rest)))}° | ${r1(q(x, 0.1))}° | **${r1(median(x))}°** | ${r1(q(x, 0.9))}° |`);
  };
  row(st.good.name, good);
  row(st.poor.name, poor);
  md.push("");

  const checks = ex.checks.filter((c) => !st.skip?.includes(c.id));
  if (checks.length) {
    md.push(`| form check | threshold | ${st.good.name} p50 / p90 | ${st.poor.name} p50 / p90 | flagged: ${st.good.name} | flagged: ${st.poor.name} |`, "|---|---|---|---|---|---|");
    for (const c of checks) {
      const g = good.map((e) => e.checks[c.id]).filter((x) => x !== undefined);
      const b = poor.map((e) => e.checks[c.id]).filter((x) => x !== undefined);
      const hit = (xs: number[]) => xs.filter((x) => (c.op === ">" ? x > c.threshold : x < c.threshold)).length / Math.max(1, xs.length);
      const pick = (xs: number[], p: number) => r1(q(xs, c.op === ">" ? p : 1 - p));
      const unit = c.relative === "percent" ? "%" : METRICS[c.metric].unit;
      md.push(
        `| ${c.label}${c.relative ? " (Δ)" : ""} | ${c.op} ${c.threshold}${unit} | ${pick(g, 0.5)} / ${pick(g, 0.9)} | ${pick(b, 0.5)} / ${pick(b, 0.9)} | ${Math.round(100 * hit(g))}% | ${Math.round(100 * hit(b))}% |`,
      );
    }
    md.push("");
  }
  console.log(`${ex.id.padEnd(20)} ${st.datasets.join(",").padEnd(36)} good ${good.length} poor ${poor.length}  end-range ${r1(median(good.map((e) => e.excursion)))} vs ${r1(median(poor.map((e) => e.excursion)))}`);
}

mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(join(ROOT, "docs", "calibration-rehabpile.md"), md.join("\n") + "\n");
console.log("wrote docs/calibration-rehabpile.md");
